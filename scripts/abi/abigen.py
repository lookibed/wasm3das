def md_params(params):
    return ", ".join("%s: %s" % (p["name"], p["type"]) for p in params)


def gen_reference(packages, worlds):
    o = ["# Eden guest ABI reference\n\n",
         "<!-- " + GEN_NOTE.format(src="*.json") + " -->\n\n",
         "The rules behind these tables are in `ABI.md`.\n\n"]
    for name in sorted(worlds):
        w = worlds[name]
        o.append("## World `%s` v%d\n\n%s\n\n" % (name, w["version"], w["doc"]))
        if w.get("extends"):
            o.append("Extends `%s`.\n\n" % w["extends"])
        o.append("Packages: %s.\n\n" % ", ".join("`%s`" % p for p in w["imports"]))
        o.append("| Export | Required | Doc |\n| --- | --- | --- |\n")
        for e in w["exports"]:
            o.append("| `%s(%s) -> %s` | %s | %s |\n" % (e["name"], md_params(e["params"]), e["result"], "yes" if e["required"] else "no", e["doc"]))
        o.append("\n")
        for c in w.get("constants", []):
            o.append("- `%s_%s = %d`: %s\n" % (name.upper(), c["name"], c["value"], c["doc"]))
        o.append("\n")
    for name in sorted(packages):
        p = packages[name]
        o.append("## Package `%s` v%d\n\n%s\n\n" % (name, p["version"], p["doc"]))
        o.append("| Import | Doc |\n| --- | --- |\n")
        for fn in p["functions"]:
            o.append("| `%s(%s) -> %s` | %s |\n" % (fn["name"], md_params(fn["params"]), fn["result"], fn["doc"]))
        o.append("\n")
        for c in p.get("constants", []):
            o.append("- `%s_%s = %d`: %s\n" % (name.upper(), c["name"], c["value"], c["doc"]))
        o.append("\n")
    return "".join(o)


def outputs(packages, worlds):
    out = {}
    for name, p in packages.items():
        out[os.path.join(DAS_OUT, "abi_%s.das" % name)] = gen_das_package(p)
        out[os.path.join(C_OUT, "%s.h" % name)] = gen_c_package(p)
    for name, w in worlds.items():
        out[os.path.join(DAS_OUT, "abi_%s.das" % name)] = gen_das_world(w, worlds)
        out[os.path.join(C_OUT, "%s.h" % name)] = gen_c_world(w, worlds)
    out[DOC_OUT] = gen_reference(packages, worlds)
    return out


def main():
    check = "--check" in sys.argv[1:]
    try:
        packages, worlds = load_idl()
        validate(packages, worlds)
    except (IdlError, KeyError, ValueError) as e:
        print("abigen: IDL error: %s" % e)
        return 2
    out = outputs(packages, worlds)
    stale = []
    for path, text in sorted(out.items()):
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                old = f.read()
        if old != text:
            stale.append(os.path.relpath(path, REPO))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    managed = {os.path.normpath(p) for p in out}
    extra = []
    for d, ext in ((DAS_OUT, ".das"), (C_OUT, ".h")):
        if os.path.isdir(d):
            for fn in os.listdir(d):
                p = os.path.normpath(os.path.join(d, fn))
                if fn.endswith(ext) and p not in managed:
                    extra.append(os.path.relpath(p, REPO))
    if check:
        for s in stale:
            print("abigen: out of date: %s" % s)
        for s in extra:
            print("abigen: not produced by the IDL (delete it): %s" % s)
        if stale or extra:
            print("abigen: run python3 scripts/abi/abigen.py")
            return 1
        print("abigen: up to date (%d packages, %d worlds, %d files)" % (len(packages), len(worlds), len(out)))
        return 0
    for s in stale:
        print("abigen: wrote %s" % s)
    for s in extra:
        print("abigen: warning: stale generated file not produced by the IDL: %s" % s)
    print("abigen: %d packages, %d worlds, %d files (%d changed)" % (len(packages), len(worlds), len(out), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
