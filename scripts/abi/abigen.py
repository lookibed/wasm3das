def gen_das_package(p):
    name = p["package"]
    host = pascal(name) + "Host"
    prefix = name.upper()
    o = []
    o.append("options gen2\noptions indenting = 4\n\n")
    o.append("// " + GEN_NOTE.format(src=p["_file"]) + "\n\n")
    o.append("module abi_%s shared public\n\n" % name)
    o.append("require %s/abi_runtime public\n" % REQUIRE_ROOT)
    o.append("require strings\n\n\n")
    o.append("/*\n    Package %s, version %d: %s\n\n" % (name, p["version"], p["doc"]))
    o.append("    The host implements %s (every field must be set; abi_link_%s\n" % (host, name))
    o.append("    refuses a null one) and links it into an instance. Each\n")
    o.append("    implementation receives the runtime (for AbiBytes access) and the\n")
    o.append("    instance id (the key of any per-instance state it keeps). To fail\n")
    o.append("    the guest it calls abi_trap(message) and returns.\n*/\n\n\n")
    o.append("let public %s_VERSION = %d\n" % (prefix, p["version"]))
    for c in p.get("constants", []):
        o.append("let public %s_%s = %d   // %s\n" % (prefix, c["name"], c["value"], c["doc"]))
    o.append("\n\nstruct %s {\n" % host)
    for fn in p["functions"]:
        o.append(das_comment_block(fn["doc"], "    "))
        args = ["var rt : M3Runtime", "inst : int"] + ["%s : %s" % (a["name"], DAS_TYPE[a["type"]]) for a in fn["params"]]
        o.append("    %s : function<(%s) : %s>\n" % (fn["name"], "; ".join(args), DAS_TYPE[fn["result"]]))
    o.append("}\n\n\n")
    o.append("var private g_impls : table<int; %s>\n\n\n" % host)
    for fn in p["functions"]:
        o.append(gen_das_wrapper(p, fn, host))
    o.append("def private abi_unlink_%s(id : int) {\n    g_impls |> erase(id)\n}\n\n\n" % name)
    o.append("// links every import of %s the guest has; refuses an implementation\n" % name)
    o.append("// with a null function\n")
    o.append("def public abi_link_%s(var inst : AbiInstance; impl : %s) : M3Result {\n" % (name, host))
    o.append("    if (!inst.alive) {\n        return \"{inst.name}: link %s: the instance is not alive\"\n    }\n" % name)
    o.append("    if (abi_is_linked(inst, \"%s\") && !inst.relinking) {\n        return \"{inst.name}: %s is already linked\"\n    }\n" % (name, name))
    o.append("    if (!abi_is_linked(inst, \"%s\") && inst.relinking) {\n        return \"{inst.name}: relink of %s, which was not linked before\"\n    }\n" % (name, name))
    for fn in p["functions"]:
        o.append("    if (impl.%s == null) {\n        return \"{inst.name}: %s.%s has no host implementation\"\n    }\n" % (fn["name"], name, fn["name"]))
    o.append("    g_impls[inst.id] = impl\n")
    o.append("    abi_register_package(inst, \"%s\", @@abi_unlink_%s)\n" % (name, name))
    o.append("    var r : M3Result = m3Err_none\n")
    for fn in p["functions"]:
        o.append("    r = abi_link_one(inst, \"%s\", \"%s\", \"%s\", @@abi_imp_%s_%s)\n" % (name, fn["name"], signature(fn["params"], fn["result"]), name, fn["name"]))
        o.append("    if (r != m3Err_none) {\n        return r\n    }\n")
    o.append("    return m3Err_none\n}\n")
    return "".join(o)


def gen_das_wrapper(p, fn, host):
    name = p["package"]
    o = []
    o.append("// %s.%s %s\n" % (name, fn["name"], signature(fn["params"], fn["result"])))
    o.append("def public abi_imp_%s_%s(var rt : M3Runtime; ctx : M3ImportContext; sp : int) : M3Result {\n" % (name, fn["name"]))
    o.append("    var f = m3ApiFrame(sp)\n")
    if fn["result"] != "void":
        o.append("    let raw_return = m3ApiReturnType(f)\n")
    need_r = any(a["type"] in ("str", "bytes", "outbuf") for a in fn["params"])
    if need_r:
        o.append("    var r : M3Result = m3Err_none\n")
    for a in fn["params"]:
        v = "a_" + a["name"]
        t = a["type"]
        if t == "str":
            o.append("    var %s = \"\"\n    r = abi_get_str(rt, f, %s)\n" % (v, v))
            o.append("    if (r != m3Err_none) {\n        return abi_trap_message(\"%s\", \"%s\", \"%s: {r}\")\n    }\n" % (name, fn["name"], a["name"]))
        elif t in ("bytes", "outbuf"):
            o.append("    var %s = AbiBytes()\n    r = abi_get_bytes(rt, f, %s)\n" % (v, v))
            o.append("    if (r != m3Err_none) {\n        return abi_trap_message(\"%s\", \"%s\", \"%s: {r}\")\n    }\n" % (name, fn["name"], a["name"]))
        else:
            o.append("    let %s = %s\n" % (v, GETTER[t]))
    o.append("    let id = m3_GetUserData(rt)\n")
    o.append("    var impl = %s()\n    var found = false\n" % host)
    o.append("    g_impls |> get(id) $(v) {\n        impl = v\n        found = true\n    }\n")
    o.append("    if (!found) {\n        return abi_trap_message(\"%s\", \"%s\", \"no implementation for instance {id}\")\n    }\n" % (name, fn["name"]))
    call_args = ", ".join(["rt", "id"] + ["a_" + a["name"] for a in fn["params"]])
    if fn["result"] == "void":
        o.append("    invoke(impl.%s, %s)\n" % (fn["name"], call_args))
    else:
        o.append("    let value = invoke(impl.%s, %s)\n" % (fn["name"], call_args))
    o.append("    let trap = abi_take_trap()\n")
    o.append("    if (!empty(trap)) {\n        return abi_trap_message(\"%s\", \"%s\", trap)\n    }\n" % (name, fn["name"]))
    if fn["result"] != "void":
        o.append("    %s\n" % RETURNER[fn["result"]].format(v="value"))
    o.append("    return m3Err_none\n}\n\n\n")
    return "".join(o)


