def gen_das_world(w, worlds):
    name = w["world"]
    chain = world_chain(worlds, name)
    prefix = name.upper()
    all_pkgs = [pkg for ww in chain for pkg in ww["imports"]]
    all_exports = [e for ww in chain for e in ww["exports"]]
    version_owner = next((ww for ww in chain if any(e["name"] == "eden_abi_version" for e in ww["exports"])), None)
    o = []
    o.append("options gen2\noptions indenting = 4\n\n")
    o.append("// " + GEN_NOTE.format(src=w["_file"]) + "\n\n")
    o.append("module abi_%s shared public\n\n" % name)
    o.append("require %s/abi_runtime public\n" % REQUIRE_ROOT)
    o.append("require strings\n")
    if w.get("extends"):
        o.append("require %s/gen/abi_%s public\n" % (REQUIRE_ROOT, w["extends"]))
    for pkg in w["imports"]:
        o.append("require %s/gen/abi_%s public\n" % (REQUIRE_ROOT, pkg))
    o.append("\n\n/*\n    World %s, version %d: %s\n" % (name, w["version"], w["doc"]))
    if w.get("extends"):
        o.append("    Extends %s.\n" % w["extends"])
    o.append("\n    Packages: %s.\n" % ", ".join(all_pkgs))
    o.append("    After linking the packages, abi_bind_%s checks the imports, finds\n" % name)
    o.append("    the exports and the version; the abi_<export> functions call them.\n*/\n\n\n")
    o.append("let public %s_VERSION = %d\n" % (prefix, w["version"]))
    for c in w.get("constants", []):
        o.append("let public %s_%s = %d   // %s\n" % (prefix, c["name"], c["value"], c["doc"]))
    o.append("\n\n")
    for e in w["exports"]:
        o.append(gen_das_export(e))
    req = [e["name"] for e in all_exports if e["required"]]
    opt = [e["name"] for e in all_exports if not e["required"]]
    o.append("// imports resolved and in the world, required exports present, version\n")
    o.append("def public abi_bind_%s(var inst : AbiInstance) : M3Result {\n" % name)
    o.append("    if (!inst.alive) {\n        return \"{inst.name}: bind %s: the instance is not alive\"\n    }\n" % name)
    o.append("    var packages : array<string>\n")
    for pkg in all_pkgs:
        o.append("    push(packages, \"%s\")\n" % pkg)
    o.append("    var r = abi_check_imports(inst, \"%s\", packages)\n" % name)
    o.append("    if (r != m3Err_none) {\n        return r\n    }\n")
    o.append("    var required : array<string>\n    var optional : array<string>\n")
    for n in req:
        o.append("    push(required, \"%s\")\n" % n)
    for n in opt:
        o.append("    push(optional, \"%s\")\n" % n)
    o.append("    r = abi_bind_exports(inst, required, optional)\n")
    o.append("    if (r != m3Err_none) {\n        return r\n    }\n")
    if version_owner is not None:
        o.append("    let version = abi_eden_abi_version(inst)\n")
        o.append("    if (!empty(inst.error)) {\n        return inst.error\n    }\n")
        o.append("    if (version != %d) {\n        return \"{inst.name}: built for world version {version}, the host supports %s version %d\"\n    }\n"
                 % (version_owner["version"], version_owner["world"], version_owner["version"]))
    o.append("    inst.world = \"%s\"\n    return m3Err_none\n}\n" % name)
    return "".join(o)


def gen_das_export(e):
    params = e["params"]
    res = e["result"]
    args = ["var inst : AbiInstance"] + ["a_%s : %s" % (p["name"], DAS_EXPORT_ARG[p["type"]]) for p in params]
    ret = "" if res == "void" else " : " + DAS_TYPE[res]
    fail = "return" if res == "void" else "return " + DAS_DEFAULT[res]
    o = []
    o.append(das_comment_block(e["doc"] + (" Optional export: check abi_has_export first." if not e["required"] else "")))
    o.append("// On failure returns %s and inst.error says why.\n" % ("nothing" if res == "void" else DAS_DEFAULT[res]))
    o.append("def public abi_%s(%s)%s {\n" % (e["name"], "; ".join(args), ret))
    o.append("    if (!inst.faulted) {\n        inst.error = \"\"\n    }\n")
    # inscope: the temporaries are freed at the end of the call (the script
    # heap is only collected between engine frames)
    o.append("    var inscope args : array<uint64>\n")
    placed = [p for p in params if p["type"] in ("str", "bytes")]
    if placed:
        o.append("    var inscope placed : array<int>\n")
    for p in params:
        v = "a_" + p["name"]
        if p["type"] in ("str", "bytes"):
            placer = "abi_place_str" if p["type"] == "str" else "abi_place_bytes"
            o.append("    let p_%s = %s(inst, %s)\n" % (p["name"], placer, v))
            o.append("    if (p_%s == 0) {\n" % p["name"])
            o.append("        for (q in placed) {\n            abi_free_guest(inst, q)\n        }\n")
            o.append("        %s\n    }\n" % fail)
            o.append("    push(placed, p_%s)\n" % p["name"])
            o.append("    push(args, m3_bits_from_i32(p_%s))\n" % p["name"])
            o.append("    push(args, m3_bits_from_i32(length(%s)))\n" % v)
        else:
            o.append("    push(args, %s)\n" % TO_BITS[p["type"]].format(v=v))
    o.append("    var inscope rets : array<uint64>\n")
    o.append("    let ok = abi_call(inst, \"%s\", args, rets)\n" % e["name"])
    if placed:
        o.append("    for (q in placed) {\n        abi_free_guest(inst, q)\n    }\n")
    if res == "void":
        o.append("    if (!ok) {\n        return\n    }\n")
    else:
        o.append("    if (!ok || length(rets) < 1) {\n        return %s\n    }\n" % DAS_DEFAULT[res])
        o.append("    return %s\n" % FROM_BITS[res].format(v="rets[0]"))
    o.append("}\n\n\n")
    return "".join(o)


