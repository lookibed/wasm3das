def c_params(params, const_bytes=True):
    out = []
    for p in params:
        t = p["type"]
        if t == "str":
            out += ["const char *%s" % p["name"], "int32_t %s_len" % p["name"]]
        elif t == "bytes":
            out += ["const void *%s" % p["name"], "int32_t %s_len" % p["name"]]
        elif t == "outbuf":
            out += ["void *%s" % p["name"], "int32_t %s_cap" % p["name"]]
        else:
            out.append("%s %s" % (C_TYPE[t], p["name"]))
    return ", ".join(out) if out else "void"


def c_comment(text, indent=""):
    return "%s/* %s */\n" % (indent, text)


def gen_c_package(p):
    name = p["package"]
    guard = "EDEN_ABI_%s_H" % name.upper()
    prefix = name.upper()
    o = []
    o.append("/* " + GEN_NOTE.format(src=p["_file"]) + " */\n")
    o.append("#ifndef %s\n#define %s\n\n#include <stdint.h>\n\n" % (guard, guard))
    o.append(c_comment("Package %s, version %d: %s" % (name, p["version"], p["doc"])))
    o.append("\n#define %s_VERSION %d\n" % (prefix, p["version"]))
    for c in p.get("constants", []):
        o.append("#define %s_%s (%d) /* %s */\n" % (prefix, c["name"], c["value"], c["doc"]))
    o.append("\n")
    for fn in p["functions"]:
        o.append(c_comment(fn["doc"]))
        o.append("__attribute__((import_module(\"%s\"), import_name(\"%s\")))\n" % (name, fn["name"]))
        o.append("%s %s_%s(%s);\n" % (C_TYPE[fn["result"]], name, fn["name"], c_params(fn["params"])))
        strs = [a for a in fn["params"] if a["type"] == "str"]
        if strs:
            cp, call = [], []
            for a in fn["params"]:
                if a["type"] == "str":
                    cp.append("const char *%s" % a["name"])
                    call += [a["name"], "(int32_t)__builtin_strlen(%s)" % a["name"]]
                elif a["type"] == "bytes":
                    cp += ["const void *%s" % a["name"], "int32_t %s_len" % a["name"]]
                    call += [a["name"], a["name"] + "_len"]
                elif a["type"] == "outbuf":
                    cp += ["void *%s" % a["name"], "int32_t %s_cap" % a["name"]]
                    call += [a["name"], a["name"] + "_cap"]
                else:
                    cp.append("%s %s" % (C_TYPE[a["type"]], a["name"]))
                    call.append(a["name"])
            ret = "" if fn["result"] == "void" else "return "
            o.append("static inline %s %s_%s_z(%s) {\n    %s%s_%s(%s);\n}\n" % (
                C_TYPE[fn["result"]], name, fn["name"], ", ".join(cp), ret, name, fn["name"], ", ".join(call)))
        o.append("\n")
    o.append("#endif\n")
    return "".join(o)


def gen_c_world(w, worlds):
    name = w["world"]
    guard = "EDEN_ABI_%s_H" % name.upper()
    prefix = name.upper()
    o = []
    o.append("/* " + GEN_NOTE.format(src=w["_file"]) + " */\n")
    o.append("#ifndef %s\n#define %s\n\n#include <stdint.h>\n" % (guard, guard))
    if w.get("extends"):
        o.append("#include \"%s.h\"\n" % w["extends"])
    for pkg in w["imports"]:
        o.append("#include \"%s.h\"\n" % pkg)
    o.append("\n" + c_comment("World %s, version %d: %s The guest defines the exports below." % (name, w["version"], w["doc"])))
    o.append("\n#define %s_VERSION %d\n" % (prefix, w["version"]))
    for c in w.get("constants", []):
        o.append("#define %s_%s (%d) /* %s */\n" % (prefix, c["name"], c["value"], c["doc"]))
    o.append("\n")
    for e in w["exports"]:
        o.append(c_comment(e["doc"] + ("" if e["required"] else " (optional)")))
        o.append("__attribute__((export_name(\"%s\")))\n" % e["name"])
        o.append("%s %s(%s);\n\n" % (C_TYPE[e["result"]], e["name"], c_params(e["params"])))
    o.append("#endif\n")
    return "".join(o)


