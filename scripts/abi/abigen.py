#!/usr/bin/env python3
"""
abigen: the generator of the Eden guest ABI (docs/eden-abi/ABI.md).

Reads abi/idl/*.json (packages) and abi/idl/*.world.json (worlds) and writes:
  source/abi/gen/abi_<package>.das   host bindings of a package: constants,
                                     the implementation struct, one raw-call
                                     wrapper per import, abi_link_<package>
  source/abi/gen/abi_<world>.das     world bindings: abi_bind_<world> and one
                                     typed wrapper per export
  guests/include/eden/<name>.h       the C header of each package and world
  docs/eden-abi/REFERENCE.md         the human-readable reference

Usage (from the repository):
  python3 scripts/abi/abigen.py            write every output
  python3 scripts/abi/abigen.py --check    change nothing; exit 1 if an output
                                           is missing or differs from the IDL
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
IDL = os.path.join(REPO, "abi", "idl")
DAS_OUT = os.path.join(REPO, "source", "abi", "gen")
C_OUT = os.path.join(REPO, "guests", "include", "eden")
DOC_OUT = os.path.join(REPO, "docs", "eden-abi", "REFERENCE.md")
REQUIRE_ROOT = "modules/wasm3das/source/abi"

IDENT = re.compile(r"^[a-z][a-z0-9_]*$")
SCALARS = ["i32", "i64", "f32", "f64", "bool", "handle"]
IMPORT_PARAM_TYPES = SCALARS + ["str", "bytes", "outbuf"]
EXPORT_PARAM_TYPES = SCALARS + ["str", "bytes"]
RESULT_TYPES = ["void"] + SCALARS
DAS_RESERVED = {"type", "string", "var", "let", "def", "struct", "class", "in", "out", "result", "self", "true", "false", "null", "range"}

DAS_TYPE = {"i32": "int", "i64": "int64", "f32": "float", "f64": "double", "bool": "bool",
            "handle": "int", "str": "string", "bytes": "AbiBytes", "outbuf": "AbiBytes", "void": "void"}
DAS_EXPORT_ARG = {"i32": "int", "i64": "int64", "f32": "float", "f64": "double", "bool": "bool",
                  "handle": "int", "str": "string", "bytes": "array<uint8>"}
DAS_DEFAULT = {"i32": "0", "i64": "0l", "f32": "0.0f", "f64": "0.0lf", "bool": "false", "handle": "0"}
SIG_CHAR = {"i32": "i", "i64": "I", "f32": "f", "f64": "F", "bool": "i", "handle": "i", "str": "ii",
            "bytes": "ii", "outbuf": "ii", "void": "v"}
C_TYPE = {"i32": "int32_t", "i64": "int64_t", "f32": "float", "f64": "double", "bool": "int32_t",
          "handle": "int32_t", "void": "void"}
GETTER = {"i32": "m3ApiGetArg_i32(rt, f)", "i64": "m3ApiGetArg_i64(rt, f)", "f32": "m3ApiGetArg_f32(rt, f)",
          "f64": "m3ApiGetArg_f64(rt, f)", "bool": "abi_get_bool(rt, f)", "handle": "m3ApiGetArg_i32(rt, f)"}
RETURNER = {"i32": "m3ApiReturn_i32(rt, raw_return, {v})", "i64": "m3ApiReturn_i64(rt, raw_return, {v})",
            "f32": "m3ApiReturn_f32(rt, raw_return, {v})", "f64": "m3ApiReturn_f64(rt, raw_return, {v})",
            "bool": "m3ApiReturn_i32(rt, raw_return, {v} ? 1 : 0)", "handle": "m3ApiReturn_i32(rt, raw_return, {v})"}
TO_BITS = {"i32": "m3_bits_from_i32({v})", "i64": "m3_bits_from_i64({v})", "f32": "m3_bits_from_f32({v})",
           "f64": "m3_bits_from_f64({v})", "bool": "m3_bits_from_i32({v} ? 1 : 0)", "handle": "m3_bits_from_i32({v})"}
FROM_BITS = {"i32": "m3_bits_to_i32({v})", "i64": "m3_bits_to_i64({v})", "f32": "m3_bits_to_f32({v})",
             "f64": "m3_bits_to_f64({v})", "bool": "(m3_bits_to_i32({v}) != 0)", "handle": "m3_bits_to_i32({v})"}

GEN_NOTE = "GENERATED by scripts/abi/abigen.py from abi/idl/{src} - do not edit; change the IDL and regenerate"


class IdlError(Exception):
    pass


def pascal(name):
    return "".join(p.capitalize() for p in name.split("_"))


def check_ident(what, name):
    if not isinstance(name, str) or not IDENT.match(name):
        raise IdlError("%s: %r is not a lower_snake identifier" % (what, name))


def check_doc(what, obj):
    if not isinstance(obj.get("doc"), str) or not obj["doc"].strip():
        raise IdlError("%s: missing doc" % what)


def load_idl():
    packages, worlds = {}, {}
    for fn in sorted(os.listdir(IDL)):
        if not fn.endswith(".json"):
            continue
        with open(os.path.join(IDL, fn), encoding="utf-8") as f:
            data = json.load(f)
        data["_file"] = fn
        if fn.endswith(".world.json"):
            worlds[data["world"]] = data
        else:
            packages[data["package"]] = data
    return packages, worlds


def validate(packages, worlds):
    for name, p in packages.items():
        where = p["_file"]
        check_ident(where + " package", name)
        if p["_file"] != name + ".json":
            raise IdlError("%s: the file must be named %s.json" % (where, name))
        check_doc(where, p)
        if not isinstance(p.get("version"), int) or p["version"] < 1:
            raise IdlError("%s: version must be a positive integer" % where)
        seen = set()
        for c in p.get("constants", []):
            if not re.match(r"^[A-Z][A-Z0-9_]*$", c["name"]) or not isinstance(c["value"], int):
                raise IdlError("%s: constant %r must be UPPER_SNAKE with an integer value" % (where, c))
            check_doc("%s constant %s" % (where, c["name"]), c)
        for fn in p["functions"]:
            fw = "%s function %s" % (where, fn.get("name"))
            check_ident(fw, fn["name"])
            check_doc(fw, fn)
            if fn["name"] in seen:
                raise IdlError(fw + ": duplicate")
            seen.add(fn["name"])
            pnames = set()
            for prm in fn["params"]:
                check_ident(fw + " param", prm["name"])
                if prm["name"] in pnames:
                    raise IdlError(fw + ": duplicate param " + prm["name"])
                pnames.add(prm["name"])
                if prm["type"] not in IMPORT_PARAM_TYPES:
                    raise IdlError("%s: param %s has type %s; imports take %s" % (fw, prm["name"], prm["type"], IMPORT_PARAM_TYPES))
            if fn["result"] not in RESULT_TYPES:
                raise IdlError("%s: result %s; allowed %s" % (fw, fn["result"], RESULT_TYPES))
    export_owner = {}
    for name, w in worlds.items():
        where = w["_file"]
        check_ident(where + " world", name)
        if w["_file"] != name + ".world.json":
            raise IdlError("%s: the file must be named %s.world.json" % (where, name))
        check_doc(where, w)
        base = w.get("extends")
        if base is not None and base not in worlds:
            raise IdlError("%s: extends unknown world %s" % (where, base))
        for pkg in w["imports"]:
            if pkg not in packages:
                raise IdlError("%s: imports unknown package %s" % (where, pkg))
        for c in w.get("constants", []):
            if not re.match(r"^[A-Z][A-Z0-9_]*$", c["name"]) or not isinstance(c["value"], int):
                raise IdlError("%s: constant %r must be UPPER_SNAKE with an integer value" % (where, c))
        for e in w["exports"]:
            ew = "%s export %s" % (where, e.get("name"))
            check_ident(ew, e["name"])
            check_doc(ew, e)
            if e["name"] in export_owner:
                raise IdlError("%s: export name already used by world %s (export names are unique across worlds)" % (ew, export_owner[e["name"]]))
            export_owner[e["name"]] = name
            if not isinstance(e.get("required"), bool):
                raise IdlError(ew + ": `required` must be true or false")
            for prm in e["params"]:
                check_ident(ew + " param", prm["name"])
                if prm["type"] not in EXPORT_PARAM_TYPES:
                    raise IdlError("%s: param %s has type %s; exports take %s" % (ew, prm["name"], prm["type"], EXPORT_PARAM_TYPES))
            if e["result"] not in RESULT_TYPES:
                raise IdlError("%s: result %s; allowed %s" % (ew, e["result"], RESULT_TYPES))
    for name, w in worlds.items():
        chain = world_chain(worlds, name)
        all_exports = [e for ww in chain for e in ww["exports"]]
        names = {e["name"] for e in all_exports}
        needs_alloc = any(p["type"] in ("str", "bytes") for e in all_exports for p in e["params"])
        if needs_alloc and not {"eden_alloc", "eden_free"} <= names:
            raise IdlError("%s: exports take str/bytes, so the world must declare eden_alloc and eden_free" % w["_file"])


def world_chain(worlds, name):
    """the world and its bases, base first"""
    chain = []
    seen = set()
    while name is not None:
        if name in seen:
            raise IdlError("world %s: extends cycle" % name)
        seen.add(name)
        chain.insert(0, worlds[name])
        name = worlds[name].get("extends")
    return chain


def signature(params, result):
    return SIG_CHAR[result] + "(" + "".join(SIG_CHAR[p["type"]] for p in params) + ")"


def das_comment_block(text, indent=""):
    words = text.split()
    lines, cur = [], ""
    for wd in words:
        if len(cur) + len(wd) + 1 > 74:
            lines.append(cur)
            cur = wd
        else:
            cur = (cur + " " + wd).strip()
    if cur:
        lines.append(cur)
    return "".join("%s// %s\n" % (indent, l) for l in lines)


